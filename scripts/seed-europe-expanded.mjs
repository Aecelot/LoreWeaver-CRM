async function seedExpandedEurope() {
  console.log(`Adding ${validLeads.length} expanded European leads...\n`);
  
  const byCountry = {};
  
  for (const lead of validLeads) {
    const docRef = await db.collection('leads').add({
      ...lead,
      createdAt: admin.firestore.FieldValue.serverTimestamp(),
      updatedAt: admin.firestore.FieldValue.serverTimestamp()
    });
    
    const priority = { high: '🔴', medium: '🟡', low: '🟢' };
    const country = lead.country;
    byCountry[country] = (byCountry[country] || 0) + 1;
    
    console.log(`${priority[lead.priority] || '⚪'} ${lead.name.padEnd(28)} | Fit: ${lead.studio.fitScore.toString().padStart(2)} | ${country.substring(0,3).toUpperCase()}`);
  }
  
  console.log(`\n✅ Done. Added ${validLeads.length} leads.`);
  Object.entries(byCountry).sort().forEach(([c, n]) => console.log(`   ${c}: ${n}`));
  process.exit(0);
}

